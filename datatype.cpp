#include<iostream>
using namespace std;
int main()
{
    int a = 5500;
    float b = 77.89;
    char ch = 'S';
    double d = 566.8988888888;
    long int l = 76000000;
    short int s = 88;
    cout<<"Integer value is "<<a<<endl;
    cout<<"Floating value is "<<b<<endl;
    cout<<"Character value is "<<ch<<endl;
    cout<<"Double value is "<<d<<endl;
    cout<<"Long Integer value is "<<l<<endl;
    cout<<"Short Integer value is "<<s<<endl;
    return 0;
}